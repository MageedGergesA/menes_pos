/**
 * The glyph for `name`, or `fallback` when the map has no such name. Returns a
 * plain string so a caller keeps using a text node — no wrapper element, and no
 * second code path for "has an icon" versus "does not".
 */
export function icon(name, fallback = "") {
    return ICONS[name] || fallback;
}

/** True when `name` renders as a real icon rather than the fallback. */
export function hasIcon(name) {
    return !!ICONS[name];
}
